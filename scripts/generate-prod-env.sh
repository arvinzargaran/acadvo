#!/usr/bin/env bash
#
# Generate a production .env with freshly-minted secrets.
#
# The point is that nobody hand-types a JWT secret or reuses the dev database
# password. Everything security-sensitive is generated here; everything
# deployment-specific is prompted for, and the script refuses to guess.
#
# Usage:
#   ./scripts/generate-prod-env.sh                 # writes .env.production
#   ./scripts/generate-prod-env.sh /path/to/.env   # writes somewhere else
#
# It never overwrites an existing file — rotating secrets under a running
# deployment logs every user out, so that has to be a deliberate act.

set -euo pipefail

OUT="${1:-.env.production}"

if [[ -e "$OUT" ]]; then
  echo "error: $OUT already exists." >&2
  echo "Refusing to overwrite it — regenerating secrets invalidates every" >&2
  echo "existing session and breaks an already-deployed database password." >&2
  echo "Move it aside first if you really mean to." >&2
  exit 1
fi

need() {
  command -v "$1" >/dev/null 2>&1 || { echo "error: '$1' is required." >&2; exit 1; }
}
need openssl
need python3

ask() {
  local prompt="$1" var="$2" value=""
  while [[ -z "$value" ]]; do
    read -r -p "$prompt" value
    [[ -z "$value" ]] && echo "  (required)"
  done
  printf -v "$var" '%s' "$value"
}

echo "Acadvo production environment"
echo "-----------------------------"
echo "Two hostnames under ONE registrable domain (e.g. acadvo.app + api.acadvo.app)."
echo "That keeps app -> API requests same-site so the SameSite=lax auth cookies work."
echo

ask "App domain          (e.g. acadvo.app)      : " APP_DOMAIN
ask "API domain          (e.g. api.acadvo.app)  : " API_DOMAIN
ask "Let's Encrypt email                        : " ACME_EMAIL
ask "Groq API key        (gsk_...)              : " GROQ_API_KEY
echo
echo "SMTP is required, not optional: verification links gate the AI features,"
echo "so without working mail no user can ever reach the advisor."
ask "SMTP host           (e.g. smtp.resend.com) : " SMTP_HOST
ask "SMTP username                              : " SMTP_USER
ask "SMTP password                              : " SMTP_PASSWORD
ask "From address        (e.g. no-reply@...)    : " EMAIL_FROM

# Secrets: generated, never prompted.
JWT_SECRET_KEY="$(openssl rand -hex 32)"
POSTGRES_PASSWORD="$(python3 -c "import secrets,string; a=string.ascii_letters+string.digits; print(''.join(secrets.choice(a) for _ in range(40)))")"

umask 077   # the file holds live credentials; nobody else on the box needs it.
cat > "$OUT" <<EOF
# Generated by scripts/generate-prod-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Contains live credentials. Never commit this file.

# ── TLS / domains ───────────────────────────────────────────────────
APP_DOMAIN=${APP_DOMAIN}
API_DOMAIN=${API_DOMAIN}
ACME_EMAIL=${ACME_EMAIL}

# ── Database ────────────────────────────────────────────────────────
POSTGRES_USER=acadvo
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=acadvo
DATABASE_URL=postgresql+asyncpg://acadvo:${POSTGRES_PASSWORD}@db:5432/acadvo
DATABASE_URL_SYNC=postgresql://acadvo:${POSTGRES_PASSWORD}@db:5432/acadvo

# ── Auth ────────────────────────────────────────────────────────────
JWT_SECRET_KEY=${JWT_SECRET_KEY}
JWT_ALGORITHM=HS256
ACCESS_TOKEN_EXPIRE_MINUTES=30
REFRESH_TOKEN_EXPIRE_DAYS=7

# ── AI ──────────────────────────────────────────────────────────────
GROQ_API_KEY=${GROQ_API_KEY}

# ── Email ───────────────────────────────────────────────────────────
FRONTEND_URL=https://${APP_DOMAIN}
SMTP_HOST=${SMTP_HOST}
SMTP_PORT=587
SMTP_USER=${SMTP_USER}
SMTP_PASSWORD=${SMTP_PASSWORD}
SMTP_STARTTLS=True
EMAIL_FROM=${EMAIL_FROM}
EMAIL_FROM_NAME=Acadvo

# ── URLs / CORS ─────────────────────────────────────────────────────
PUBLIC_API_URL=https://${API_DOMAIN}
VITE_API_URL=https://${API_DOMAIN}
CORS_ORIGINS=https://${APP_DOMAIN}

# ── Hardening (the app refuses to start if these are wrong) ─────────
COOKIE_SECURE=True
COOKIE_SAMESITE=lax
DEBUG=False
BEHIND_PROXY=True
# Caddy runs as a container, so the trusted peer is its compose-network
# address, not loopback. Must match the subnet in docker-compose.prod.yml.
FORWARDED_ALLOW_IPS=172.28.0.0/16
RATE_LIMIT_STORAGE_URI=

# ── Error tracking (optional but recommended) ───────────────────────
SENTRY_DSN=
SENTRY_TRACES_SAMPLE_RATE=0.0
EOF

chmod 600 "$OUT"

echo
echo "Wrote $OUT (mode 600)."
echo
echo "Generated for you:  JWT_SECRET_KEY (32 bytes), POSTGRES_PASSWORD (40 chars)"
echo "Still to consider:  SENTRY_DSN, an uptime monitor on both hostnames,"
echo "                    and a cron entry for ./scripts/backup-db.sh with the"
echo "                    dumps copied OFF this host."
echo
echo "Deploy with:"
echo "  cp $OUT .env"
echo "  docker compose -f docker-compose.prod.yml up -d --build"
