export function getScale(university) {
  if (university && GRADING_SCALES[university]) {
    return { scale: GRADING_SCALES[university], isFallback: false };
  }
  return { scale: FALLBACK_SCALE, isFallback: true };
}

export function buildGradeMap(scale) {
  const map = {};
  for (const g of scale.grades) {
    map[g.letter.toUpperCase()] = g.points;
  }
  return map;
}

